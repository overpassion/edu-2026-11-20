-- ===================================================================
-- eGovFrame 5.0 Boot 게시판 스키마 (HSQLDB)
-- 과제 기준 DDL: BOARD(BOARD_ID, TITLE, CONTENT, WRITER)
-- HIT(조회수), REG_DT(작성일) 및 첨부파일 테이블은 자유롭게 추가.
-- ===================================================================

DROP TABLE IF EXISTS BOARD_FILE_ATT;
DROP TABLE IF EXISTS BOARD;
DROP SEQUENCE IF EXISTS SEQ_BOARD;
DROP SEQUENCE IF EXISTS SEQ_BOARD_FILE;

-- 게시글
CREATE TABLE BOARD (
    BOARD_ID   VARCHAR(20)  NOT NULL,
    TITLE      VARCHAR(200) NOT NULL,
    CONTENT    VARCHAR(4000),
    WRITER     VARCHAR(50)  NOT NULL,
    HIT        INTEGER      DEFAULT 0   NOT NULL,
    REG_DT     TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PRIMARY KEY (BOARD_ID)
);

-- 첨부파일
CREATE TABLE BOARD_FILE_ATT (
    FILE_ID    VARCHAR(20)   NOT NULL,
    BOARD_ID   VARCHAR(20)   NOT NULL,
    FILE_NM    VARCHAR(255)  NOT NULL,   -- 원래 파일명
    FILE_PATH  VARCHAR(1000) NOT NULL,   -- 서버 저장 파일명
    FILE_SIZE  BIGINT        DEFAULT 0   NOT NULL,
    REG_DT     TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PRIMARY KEY (FILE_ID)
);

-- 게시판 ID 발급용 시퀀스
CREATE SEQUENCE SEQ_BOARD       START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_BOARD_FILE  START WITH 1 INCREMENT BY 1;
